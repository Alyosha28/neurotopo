class QualificationGateError(RuntimeError):
    """The frozen qualification-to-formal dependency has not been met."""


@dataclass(frozen=True)
class QualificationAdmission:
    lr_rs_sc: float
    lr_dense: float
    qualification_manifest_sha256: str
    qualification_analysis_sha256: str
    qualification_review_sha256: str
    qualification_decision_sha256: str
    qualification_reflection: dict[str, str]
    data_generation_p95_seconds: float
    ood_mean_windows: dict[str, list[float]]
    ood_per_seed_windows: dict[str, list[float]]


def _sha(path: Path) -> str:
    if not path.is_file() or path.is_symlink():
        raise QualificationGateError(f"required unaliased file missing: {path}")
    return sha256(path.read_bytes()).hexdigest()


def _read_json(path: Path) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise QualificationGateError(f"invalid JSON: {path}") from exc
    if not isinstance(data, dict):
        raise QualificationGateError(f"expected JSON object: {path}")
    return data


def _locked_reference(root: Path, record: dict[str, Any]) -> Path:
    relative = Path(record["path"])
    if relative.is_absolute() or ".." in relative.parts:
        raise QualificationGateError("lock reference must stay inside project")
    path = root / relative
    if not path.resolve().is_relative_to(root.resolve()):
        raise QualificationGateError("lock reference resolves outside project")
    if _sha(path) != record["sha256"]:
        raise QualificationGateError(f"frozen byte mismatch: {relative}")
    return path


def _evidence_file(record: dict[str, Any], expected_sha: str | None = None) -> Path:
    if not isinstance(record, dict) or not isinstance(record.get("path"), str):
        raise QualificationGateError("missing ResearchLoop evidence record")
    path = Path(record["path"])
    digest = _sha(path)
    if digest != record.get("sha256") or (expected_sha is not None and digest != expected_sha):
        raise QualificationGateError(f"ResearchLoop evidence hash mismatch: {path}")
    if record.get("size") != path.stat().st_size:
        raise QualificationGateError(f"ResearchLoop evidence size mismatch: {path}")
    return path


def _ledger_qualification(loop_root: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    ledger = loop_root / "iteration_log.jsonl"
    try:
        events = [json.loads(line) for line in ledger.read_text(encoding="utf-8").splitlines() if line]
    except (OSError, ValueError) as exc:
        raise QualificationGateError("EXP-0013 ResearchLoop ledger missing or invalid") from exc
    if not events:
        raise QualificationGateError("empty ResearchLoop ledger")
    # The append-only event stream, rather than its materialized progress view,
    # is the authority.  Require an uninterrupted phase chain for this entry.
    begins = [i for i, event in enumerate(events)
              if event.get("kind") == "begin" and event.get("experiment") == "EXP-0013"]
    if len(begins) != 1:
        raise QualificationGateError("exactly one EXP-0013 begin required")
    start = begins[0]
    entry = events[start]["progress"]["current"]
    iteration = entry["id"]
    phase_events = [events[start]]
    for event in events[start + 1:]:
        if event.get("progress", {}).get("current", {}).get("id") != iteration:
            break
        if event.get("kind") == "advance":
            phase_events.append(event)
    observed = [event["progress"]["phase"] for event in phase_events]
    if observed != list(PHASES):
        raise QualificationGateError(f"EXP-0013 incomplete phase chain: {observed}")
    final = phase_events[-1]["progress"]
    current = final["current"]
    if current.get("experiment") != "EXP-0013" or current.get("decision") != "SUPPORTED":
        raise QualificationGateError("EXP-0013 independent decision is not SUPPORTED")
    # The substatus must be present in the independent decision evidence too;
    # a qualification analysis may only say pending independent review.
    decision_path = _evidence_file(current["evidence"]["DECIDED"])
    review_path = _evidence_file(current["evidence"]["REVIEWED"])
    try:
        review = _read_json(review_path)
    except QualificationGateError as exc:
        raise QualificationGateError("EXP-0013 independent review must be structured JSON") from exc
    if review.get("verdict") != "CONTROL_STRONG_ENOUGH":
        raise QualificationGateError("independent review did not accept CONTROL_STRONG_ENOUGH")
    if "CONTROL_STRONG_ENOUGH" not in decision_path.read_text(encoding="utf-8"):
        raise QualificationGateError("independent decision lacks CONTROL_STRONG_ENOUGH")
    for phase in PHASES[1:]:
        _evidence_file(current["evidence"][phase])
    reflection_event = next((event for event in events[start + 1:]
                             if event.get("kind") == "reflection"
                             and event.get("progress", {}).get("current", {}).get("id") == iteration), None)
    if reflection_event is None:
        raise QualificationGateError("EXP-0013 packet-only reflection missing")
    reflected = reflection_event["progress"]["current"].get("reflection", {})
    records = reflected.get("records", {})
    if set(records) != {"packet", "review", "reaction"}:
        raise QualificationGateError("incomplete packet/review/reaction records")
    for record in records.values():
        _evidence_file(record)
    packet = _read_json(Path(records["packet"]["path"]))
    if (packet.get("design", {}).get("sha256") != current["evidence"]["REGISTERED"]["sha256"]
            or packet.get("action", {}).get("sha256") != current["evidence"]["ANALYZED"]["sha256"]):
        raise QualificationGateError("reflection packet does not bind registered and analyzed evidence")
    return current, {name: record["sha256"] for name, record in records.items()}


def qualification_gate(project_root: Path, config_path: Path,
                       loop_root: Path) -> QualificationAdmission:
    """Check frozen bytes and fully reviewed EXP-0013 before any task-root read.

    Qualification raw-array recomputation is delegated to
    ``phase_reveal_formal_analysis.recheck_qualification``; it must succeed
    before this function admits the formal run.
    """
    root = project_root.resolve()
    config_path = config_path.resolve()
    if not config_path.is_relative_to(root):
        raise QualificationGateError("config is outside project")
    if _sha(config_path) != CONFIG_SHA256:
        raise QualificationGateError("formal config differs from frozen v3 SHA")
    config = _read_json(config_path)
    if config.get("experiment_id") != "EXP-0014" or config.get("version") != "v3":
        raise QualificationGateError("wrong formal config")
    if _sha(root / config["registration_lock_file"]) != LOCK_SHA256:
        raise QualificationGateError("formal config lock differs from frozen SHA")
    lock = _read_json(root / config["registration_lock_file"])
    for ref in lock["references"].values():
        _locked_reference(root, ref)
    if lock["references"]["formal_config"]["path"] != str(config_path.relative_to(root)):
        raise QualificationGateError("config lock points elsewhere")
    pair_path = _locked_reference(root, lock["references"]["protocol_pair"])
    if _sha(pair_path) != config["pair_manifest_sha256"]:
        raise QualificationGateError("pair manifest hash differs from config")
    pair = _read_json(pair_path)
    for ref in pair["references"].values():
        _locked_reference(root, ref)
    if (pair["references"]["formal"]["sha256"]
            != lock["references"]["formal_protocol"]["sha256"]
            or pair["references"]["qualification"]["sha256"]
            != lock["references"]["qualification_protocol"]["sha256"]):
        raise QualificationGateError("pair and config lock disagree")
    qconfig = _read_json(root / lock["references"]["qualification_config"]["path"])
    if qconfig["pair_manifest_sha256"] != config["pair_manifest_sha256"]:
        raise QualificationGateError("qualification config uses another pair")
    current, reflection = _ledger_qualification(loop_root)
    source = config["qualification_source"]
    manifest = root / source["manifest_path"]
    analysis = root / source["analysis_path"]
    ledger_project = loop_root.resolve().parents[2]
    expected_ledger_analysis = (ledger_project / source["analysis_path"]).resolve()
    if Path(current["evidence"]["ANALYZED"]["path"]).resolve() != expected_ledger_analysis:
        raise QualificationGateError("loop analysis path differs from frozen main-workspace source")
    _evidence_file(current["evidence"]["ANALYZED"])
    if _sha(analysis) != current["evidence"]["ANALYZED"]["sha256"]:
        raise QualificationGateError("clean-checkout analysis differs from main-loop evidence")
    ledger_manifest = ledger_project / source["manifest_path"]
    if _sha(manifest) != _sha(ledger_manifest):
        raise QualificationGateError("clean-checkout manifest differs from main-workspace evidence")
    manifest_sha = _sha(manifest)
    if _read_json(analysis).get("source_manifest_sha256") != manifest_sha:
        raise QualificationGateError("qualification analysis does not bind its source manifest")
    manifest_data = _read_json(manifest)
    for name, expected in manifest_data.get("source_hashes", {}).items():
        source_path = _locked_reference(root, {"path": name, "sha256": expected})
        if not source_path.is_relative_to(root):
            raise QualificationGateError("qualification source path escaped project")
    if not manifest_data.get("source_hashes"):
        raise QualificationGateError("qualification source SHA records missing")
    if manifest_data.get("lock_sha256") != _sha(root / config["registration_lock_file"]):
        raise QualificationGateError("qualification lock SHA record differs")
    from .phase_reveal_formal_analysis import recheck_qualification

    try:
        checked = recheck_qualification(root, qconfig, manifest_data, _read_json(analysis))
    except (OSError, KeyError, ValueError, TypeError, FloatingPointError) as exc:
        raise QualificationGateError(f"EXP-0013 raw-array qualification audit failed: {exc}") from exc
    if checked["status"] != "NUMERIC_GUARDS_PASS_PENDING_REVIEW":
        raise QualificationGateError("EXP-0013 numeric guards did not pass")
    selected = checked["selected_lr"]
    return QualificationAdmission(
        lr_rs_sc=float(selected["SC64"]), lr_dense=float(selected["D64_full"]),
        qualification_manifest_sha256=manifest_sha,
        qualification_analysis_sha256=current["evidence"]["ANALYZED"]["sha256"],
        qualification_review_sha256=current["evidence"]["REVIEWED"]["sha256"],
        qualification_decision_sha256=current["evidence"]["DECIDED"]["sha256"],
        qualification_reflection=reflection,
        data_generation_p95_seconds=float(checked["data_generation_p95_seconds"]),
        ood_mean_windows=qconfig["qualification"]["ood_mean_windows"],
        ood_per_seed_windows=qconfig["qualification"]["ood_per_seed_windows"],
    )


def transplant_diagnostic(model: RoutedModel, x: Tensor, oracle: np.ndarray,
                          block: int, permutation_seed: int,
                          original_trace: dict[str, Any] | None = None) -> dict[str, Any]:
    """Registered t16 reachable-prefix transplant on a fixed original suffix.

    The oracle remains the original sample's full posterior.  Only the
    designated early u coordinates are permuted; early y and all later inputs
    retain their original values.
    """
    if model.name != "RS4" or x.ndim != 3 or x.shape[1] != 48 or not 0 <= block < 4:
        raise ValueError("expected RS4, [B,48,16], block 0..3")
    if oracle.shape != (x.shape[0], 4):
        raise ValueError("oracle must be [B,4]")
    from .phase_reveal_formal_analysis import kl_rows

    with torch.no_grad():
        original = original_trace if original_trace is not None else model.run_trace(x, (16, 48))
        original_h16 = original["hidden_by_time"][16]
        original_h48 = original["hidden_by_time"][48]
        original_logits = original["logits_by_time"][48]
        perm = np.random.Generator(np.random.PCG64(permutation_seed)).permutation(x.shape[0])
        prefix = x[:, :16].clone()
        prefix[:, :, 4 * block] = x[torch.as_tensor(perm, device=x.device), :16, 4 * block]
        cf_h16 = model.hidden_after_prefix(prefix)
        transplanted = original_h16.clone()
        lo, hi = 16 * block, 16 * (block + 1)
        transplanted[:, lo:hi] = cf_h16[:, lo:hi]
        cf_logits, cf_h48 = model.replay_suffix(x[:, 16:], transplanted)
        lesion_h = original_h48.clone()
        lesion_h[:, lo:hi] = 0
        lesion_logits = model.readout(lesion_h)
    arr = lambda tensor: tensor.detach().cpu().numpy().astype(np.float64)
    orig, changed, lesioned = map(arr, (original_logits, cf_logits, lesion_logits))
    difference = orig - changed
    difference -= difference.mean(axis=1, keepdims=True)
    difference -= difference.mean(axis=0, keepdims=True)
    h16_delta = arr(cf_h16[:, lo:hi]) - arr(original_h16[:, lo:hi])
    untouched16 = arr(transplanted) - arr(original_h16)
    untouched16[:, lo:hi] = 0
    untouched48 = arr(cf_h48) - arr(original_h48)
    untouched48[:, lo:hi] = 0
    return {
        "block": block, "permutation_seed": permutation_seed,
        "permutation_sha256": sha256(np.asarray(perm, dtype="<i8").tobytes()).hexdigest(),
        "state_change": float(np.linalg.norm(h16_delta, axis=1).mean() / 4),
        "non_target_t16_max": float(np.max(np.abs(untouched16))),
        "non_target_t48_max": float(np.max(np.abs(untouched48))),
        "centered_logit_change": float(np.linalg.norm(difference, axis=1).mean() / 2),
        "transplant_kl_increase": float(np.mean(kl_rows(oracle, changed) - kl_rows(oracle, orig))),
        "lesion_kl_increase": float(np.mean(kl_rows(oracle, lesioned) - kl_rows(oracle, orig))),
        "original_logits": orig, "transplant_logits": changed,
        "lesion_logits": lesioned,
        "h16_original": arr(original_h16), "h16_transplanted": arr(transplanted),
        "h48_original": arr(original_h48), "h48_transplanted": arr(cf_h48),
    }


def resource_verdict(config: dict[str, Any], accounts: dict[str, dict[str, Any]],
                     p50_ratios: dict[str, list[float]], step_p95_seconds: float,
                     data_p95_seconds: float) -> dict[str, Any]:
    """Apply frozen static, relative timing and absolute worker-budget gates."""
    expected = {"RS4": (16004, 4484), "SC64": (16004, 4484),
                "D64_full": (16004, 16004)}
    for arm, (allocated, effective) in expected.items():
        record = accounts.get(arm, {})
        if record.get("allocated_parameters") != allocated or record.get("effective_parameters") != effective:
            return {"status": "RESOURCE_MISMATCH", "reason": f"{arm} parameter count"}
    for field in ("operator_shapes", "hidden_state_floats", "pre_readout_cache_floats_per_example",
                  "dense_forward_linear_macs_per_example"):
        if accounts["RS4"][field] != accounts["SC64"][field]:
            return {"status": "RESOURCE_MISMATCH", "reason": f"RS/SC {field}"}
    expected_paths = {"train32", "infer32", "infer48"}
    if set(p50_ratios) != expected_paths or any(len(v) != config["resource"]["timing_blocks"] for v in p50_ratios.values()):
        return {"status": "RESOURCE_UNRESOLVED", "reason": "incomplete timing blocks"}
    ratios = np.asarray([v for block in p50_ratios.values() for v in block], dtype=np.float64)
    if not np.isfinite(ratios).all() or np.any(ratios <= 0):
        return {"status": "RESOURCE_UNRESOLVED", "reason": "invalid timing ratios"}
    resource = config["resource"]
    if np.any(ratios > resource["candidate_control_p50_fail_above"]):
        return {"status": "RESOURCE_MISMATCH", "reason": "p50 ratio above failure line"}
    if np.any(ratios > resource["candidate_control_p50_pass_max"]):
        return {"status": "RESOURCE_UNRESOLVED", "reason": "p50 ratio above pass line"}
    if not np.isfinite(step_p95_seconds) or not np.isfinite(data_p95_seconds) or min(step_p95_seconds, data_p95_seconds) <= 0:
        return {"status": "RESOURCE_UNRESOLVED", "reason": "invalid absolute estimate inputs"}
    estimate = (resource["absolute_estimate_multiplier"] * resource["research_update_cap"]
                * (step_p95_seconds + data_p95_seconds)
                + resource["absolute_estimate_eval_reserve_seconds"])
    return {"status": "PASS" if estimate <= resource["absolute_estimate_max_seconds"] else "RESOURCE_UNRESOLVED",
            "estimated_seconds": float(estimate), "p50_ratios": p50_ratios,
            "step_p95_seconds": float(step_p95_seconds),
            "data_p95_seconds": float(data_p95_seconds)}


def _check_graph(model: RoutedModel) -> None:
    graph = model.graph_info
    input_mask = model.input_mask[:64].detach().cpu().numpy()
    if model.name == "D64_full":
        if not np.all(input_mask == 1):
            raise AssertionError("dense arm must read all 16 inputs per unit")
    else:
        expected_input = np.zeros((64, 16), dtype=np.float32)
        for block in range(4):
            expected_input[16*block:16*(block+1), 4*block:4*(block+1)] = 1
        if not np.array_equal(input_mask, expected_input):
            raise AssertionError("sparse routed input mask differs")
    if not np.array_equal(model.input_mask.detach().cpu().numpy(), np.tile(input_mask, (3, 1))):
        raise AssertionError("input masks differ across GRU gates")
    if model.name in {"RS4", "SC64"}:
        if (graph["diagonal_connections"] != 64
                or set(graph["in_degree"]) != {16}
                or set(graph["out_degree"]) != {16}):
            raise AssertionError("sparse graph degree/self-loop mismatch")
        if model.name == "SC64" and (not graph["strongly_connected"]
                                     or graph["successful_swaps"] != graph["required_swaps"]):
            raise AssertionError("SC graph connectivity/swaps mismatch")
        if model.name == "RS4" and graph["successful_swaps"] != 0:
            raise AssertionError("RS graph changed")
    elif (graph["diagonal_connections"] != 64 or set(graph["in_degree"]) != {64}
          or set(graph["out_degree"]) != {64}):
        raise AssertionError("dense graph mismatch")
    base = model.mask[:64].detach().cpu().numpy().astype(np.uint8)
    if model.name == "RS4":
        expected_recurrent = np.zeros((64, 64), dtype=np.uint8)
        for block in range(4):
            expected_recurrent[16*block:16*(block+1), 16*block:16*(block+1)] = 1
        if not np.array_equal(base, expected_recurrent):
            raise AssertionError("RS recurrence is not four independent blocks")
    if not np.array_equal(model.mask.detach().cpu().numpy(), np.tile(base, (3, 1))):
        raise AssertionError("recurrent masks differ across GRU gates")
    if sha256(base.tobytes()).hexdigest() != graph["mask_sha256"]:
        raise AssertionError("graph mask hash mismatch")


def engineering_preflight(config: dict[str, Any], data_p95_seconds: float,
                          deadline: float) -> dict[str, Any]:
    """Random-only three-arm resource experiment; never calls ``make_batch``."""
    configure_cpu()
    started = time.monotonic()
    rcfg = config["resource"]
    rng = np.random.Generator(np.random.PCG64(rcfg["engineering_seed"]))
    x32 = torch.from_numpy(rng.standard_normal((128, 32, 16)).astype(np.float32))
    x48 = torch.from_numpy(rng.standard_normal((128, 48, 16)).astype(np.float32))
    target_pre = torch.from_numpy(rng.dirichlet(np.ones(4), size=128).astype(np.float32))
    target_final = torch.from_numpy(rng.dirichlet(np.ones(4), size=128).astype(np.float32))
    models = {arm: build_model(arm, rcfg["engineering_seed"],
                               config["model"]["graph_seed_base"] + rcfg["engineering_seed"])
              for arm in config["arms"]}
    accounts = {arm: resource_account(model, 32, 128) for arm, model in models.items()}
    for model in models.values():
        _check_graph(model)
        with torch.no_grad():
            a, b = model(x32)
            trace = model.run_trace(x48, (16, 48))
        if (a.shape != (128, 4) or b.shape != (128, 4)
                or trace["hidden_by_time"][16].shape != (128, 64)
                or trace["hidden_by_time"][48].shape != (128, 64)
                or not all(torch.isfinite(value).all() for value in (a, b))):
            raise AssertionError(f"{model.name} shape/state/finite engineering failure")
    if any(not torch.equal(left, right) for left, right in zip(
        models["RS4"].parameters(), models["SC64"].parameters(), strict=True)):
        raise AssertionError("RS/SC trainable initial tensors differ")
    optimizers = {arm: _optimizer(model, max((0.001, 0.003)), config["training"])
                  for arm, model in models.items()}
    blocks = rcfg["timing_blocks"]
    timings: dict[str, list[dict[str, list[float]]]] = {
        path: [] for path in ("train32", "infer32", "infer48")}
    updates = 0

    def action(path: str, arm: str) -> None:
        nonlocal updates
        model = models[arm]
        if path == "train32":
            _update(model, optimizers[arm], x32, target_pre, target_final,
                    config["training"]["grad_clip"])
            updates += 1
            if updates > rcfg["engineering_update_cap"]:
                raise RuntimeError("engineering update cap exceeded")
        else:
            with torch.no_grad():
                model(x32 if path == "infer32" else x48)

    for path in timings:
        for _ in range(blocks):
            record = {arm: [] for arm in config["arms"]}
            for _ in range(rcfg["warmup_repetitions"]):
                for arm in config["arms"]:
                    if time.monotonic() > deadline:
                        raise TimeoutError("engineering preflight wall cap")
                    action(path, arm)
            for _ in range(rcfg["timing_repetitions"]):
                for arm in config["arms"]:
                    if time.monotonic() > deadline:
                        raise TimeoutError("engineering preflight wall cap")
                    before = time.perf_counter()
                    action(path, arm)
                    record[arm].append(time.perf_counter() - before)
            timings[path].append(record)

    # Tiny-overfit starts from fresh, identically initialized engineering arms.
    overfit = {}
    for arm in config["arms"]:
        model = build_model(arm, rcfg["engineering_seed"],
                            config["model"]["graph_seed_base"] + rcfg["engineering_seed"])
        optimizer = _optimizer(model, 0.003, config["training"])
        with torch.no_grad():
            lp, lf = model(x32)
            first = float(-0.5 * (target_pre * torch.log_softmax(lp, -1)).sum(-1).mean()
                          -0.5 * (target_final * torch.log_softmax(lf, -1)).sum(-1).mean())
        for _ in range(rcfg["tiny_overfit_updates_per_arm"]):
            if time.monotonic() > deadline:
                raise TimeoutError("engineering preflight wall cap")
            _update(model, optimizer, x32, target_pre, target_final,
                    config["training"]["grad_clip"])
            updates += 1
            if updates > rcfg["engineering_update_cap"]:
                raise RuntimeError("engineering update cap exceeded")
        with torch.no_grad():
            lp, lf = model(x32)
            last = float(-0.5 * (target_pre * torch.log_softmax(lp, -1)).sum(-1).mean()
                         -0.5 * (target_final * torch.log_softmax(lf, -1)).sum(-1).mean())
        overfit[arm] = {"initial_loss": first, "final_loss": last,
                        "ratio": last / first, "updates": rcfg["tiny_overfit_updates_per_arm"]}
    ratios = {path: [float(np.median(block["RS4"]) / np.median(block["SC64"]))
                     for block in records] for path, records in timings.items()}
    step_p95 = max(float(np.percentile(block[arm], 95))
                   for block in timings["train32"] for arm in config["arms"])
    verdict = resource_verdict(config, accounts, ratios, step_p95, data_p95_seconds)
    if any(row["ratio"] > rcfg["tiny_overfit_final_initial_ratio_max"] for row in overfit.values()):
        verdict = {**verdict, "status": "ENGINEERING_ABORT", "reason": "tiny overfit guard failed"}
    if time.monotonic() - started > rcfg["preflight_wall_seconds_cap"]:
        verdict = {**verdict, "status": "INCOMPLETE_BUDGET", "reason": "engineering wall cap"}
    profiles = {}
    for arm, model in models.items():
        if time.monotonic() > deadline:
            raise TimeoutError("engineering preflight wall cap during operator profile")
        profiles[arm] = {
            "train32": _operator_profile(model, x32, target_pre, target_final,
                                          config["training"]),
            "infer32": _inference_profile(model, x32),
            "infer48": _inference_profile(model, x48),
        }
        updates += 1
    if updates > rcfg["engineering_update_cap"]:
        raise RuntimeError("engineering update cap exceeded in operator profile")
    if time.monotonic() - started > rcfg["preflight_wall_seconds_cap"]:
        verdict = {**verdict, "status": "INCOMPLETE_BUDGET", "reason": "engineering wall cap"}
    return {"status": verdict["status"], "verdict": verdict,
            "accounts": accounts,
            "inference48_accounts": {arm: resource_account(model, 48, 128)
                                      for arm, model in models.items()},
            "models": {arm: {"graph": model.graph_info,
                   "post_profile_sha256": _state_hash(model)} for arm, model in models.items()},
            "timings_seconds": timings, "tiny_overfit": overfit,
            "engineering_updates": updates, "seconds": time.monotonic() - started,
            "operator_profile": profiles}


def _operator_profile(model: RoutedModel, x: Tensor, pre: Tensor, final: Tensor,
                      train_config: dict[str, Any]) -> dict[str, Any]:
    # One full forward/backward/optimizer profile for this registered dense path.
    optimizer = _optimizer(model, 0.003, train_config)
    with torch.profiler.profile(activities=[torch.profiler.ProfilerActivity.CPU]) as profiler:
        _update(model, optimizer, x, pre, final, train_config["grad_clip"])
    return {row.key: {"calls": row.count, "self_cpu_time_us": row.self_cpu_time_total}
            for row in profiler.key_averages()}


def _inference_profile(model: RoutedModel, x: Tensor) -> dict[str, Any]:
    with torch.no_grad(), torch.profiler.profile(
        activities=[torch.profiler.ProfilerActivity.CPU]
    ) as profiler:
        model(x)
    return {row.key: {"calls": row.count, "self_cpu_time_us": row.self_cpu_time_total}
            for row in profiler.key_averages()}


