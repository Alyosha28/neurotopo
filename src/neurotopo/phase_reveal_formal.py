def _clean_commit(repo: Path) -> str:
    status = subprocess.run(["git", "status", "--porcelain"], cwd=repo,
                            capture_output=True, text=True, check=True)
    if status.stdout.strip():
        raise ValueError("engineering preflight requires a clean committed checkout")
    result = subprocess.run(["git", "rev-parse", "HEAD"], cwd=repo,
                            capture_output=True, text=True, check=True)
    return result.stdout.strip()


def _head_blob_matches(repo: Path, file: Path) -> None:
    """Require a regular worktree file equal to its committed HEAD blob."""
    repo = repo.resolve()
    if file.is_symlink():
        raise QualificationGateError("preflight evidence must not be a symlink")
    file = file.resolve()
    if not file.is_relative_to(repo):
        raise QualificationGateError("preflight evidence is outside clean checkout")
    relative = file.relative_to(repo).as_posix()
    worktree_sha = _sha(file)
    tree = subprocess.run(["git", "ls-tree", "HEAD", "--", relative], cwd=repo,
                          capture_output=True, text=True, check=True)
    lines = tree.stdout.splitlines()
    if len(lines) != 1 or not lines[0].startswith(("100644 blob ", "100755 blob ")) or not lines[0].endswith("\t" + relative):
        raise QualificationGateError(f"required regular file is absent from HEAD: {relative}")
    blob = subprocess.run(["git", "show", f"HEAD:{relative}"], cwd=repo,
                          capture_output=True, check=True)
    if sha256(blob.stdout).hexdigest() != worktree_sha:
        raise QualificationGateError(f"HEAD/worktree bytes differ: {relative}")


def _verified_preflight_commit(repo: Path, source_commit: str,
                               report_path: Path, receipt_path: Path,
                               terminal_path: Path) -> None:
    """All three preflight records must be committed after source commit X."""
    if not isinstance(source_commit, str) or re.fullmatch(r"[0-9a-f]{40,64}", source_commit) is None:
        raise QualificationGateError("preflight source commit is invalid")
    head_result = subprocess.run(["git", "rev-parse", "HEAD"], cwd=repo,
                                 capture_output=True, text=True, check=True)
    head = head_result.stdout.strip()
    if source_commit == head:
        raise QualificationGateError("preflight report/receipt require a later committed run checkout")
    ancestor = subprocess.run(["git", "merge-base", "--is-ancestor", source_commit, head],
                              cwd=repo, capture_output=True)
    if ancestor.returncode != 0:
        raise QualificationGateError("preflight source commit is not a true ancestor of run commit")
    for file in (report_path, receipt_path, terminal_path):
        _head_blob_matches(repo, file)


def _write_json_fsync_new(path: Path, value: dict[str, Any], *,
                          deadline: float | None = None) -> bool:
    """Publish new JSON; turn PASS into failure if file fsync exceeds deadline."""
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() or path.is_symlink():
        raise FileExistsError(f"preflight evidence already exists: {path}")
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            json.dump(value, stream, ensure_ascii=False, indent=2, sort_keys=True, allow_nan=False)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        if (deadline is not None and time.monotonic() > deadline
                and value.get("status") == "PASS"):
            # The synchronized temporary file has not been published. Rewrite
            # it as failure, sync again, and only then link the immutable path.
            value["status"] = "INCOMPLETE_BUDGET"
            with open(temporary, "w", encoding="utf-8") as stream:
                json.dump(value, stream, ensure_ascii=False, indent=2, sort_keys=True, allow_nan=False)
                stream.write("\n")
                stream.flush()
                os.fsync(stream.fileno())
        os.link(temporary, path)
        directory = os.open(path.parent, os.O_RDONLY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        Path(temporary).unlink(missing_ok=True)
    return deadline is None or time.monotonic() <= deadline


def run_preflight(config_path: Path, *, repo: Path,
                  loop_root: Path | None = None) -> dict[str, Any]:
    """Independent <=300s random-only engineering gate before VALIDATED."""
    repo = Path(repo).resolve()
    config_path = Path(config_path).resolve()
    report_path = (repo / PREFLIGHT_REPORT).resolve()
    receipt_path = (repo / PREFLIGHT_RECEIPT).resolve()
    terminal_path = (repo / PREFLIGHT_TERMINAL).resolve()
    if report_path.exists() or receipt_path.exists() or terminal_path.exists():
        raise FileExistsError("EXP-0014 preflight report/receipt/terminal already exists")
    admission = qualification_gate(repo, config_path,
                                   (loop_root or repo / "artifacts/auto_research/live").resolve())
    commit = _clean_commit(repo)
    config = _read_json(config_path)
    source = _source_hashes(repo)
    started = time.monotonic()
    try:
        engineering = engineering_preflight(config, admission.data_generation_p95_seconds,
                                             started + config["resource"]["preflight_wall_seconds_cap"])
        status = engineering["status"]
    except (TimeoutError, FloatingPointError, AssertionError, RuntimeError, ValueError) as exc:
        status = "INCOMPLETE_BUDGET" if isinstance(exc, TimeoutError) else "ENGINEERING_ABORT"
        engineering = {"status": status, "reason": repr(exc)}
    report = {"experiment_id": "EXP-0014", "version": "v3", "status": status,
              "commit": commit, "config_sha256": _sha(config_path),
              "lock_sha256": _sha(repo / config["registration_lock_file"]),
              "source_hashes": source, "qualification_admission": admission.__dict__,
              "engineering": engineering, "wall_seconds": time.monotonic() - started,
              "formal_task_roots_read": 0}
    deadline = started + config["resource"]["preflight_wall_seconds_cap"]
    _write_json_fsync_new(report_path, report, deadline=deadline)
    after_report = time.monotonic() - started
    if after_report > config["resource"]["preflight_wall_seconds_cap"] or report["status"] != "PASS":
        status = "INCOMPLETE_BUDGET"
    receipt = {"report_file": str(report_path), "report_sha256": _sha(report_path),
               "commit": commit, "status": status,
               "seconds_after_report_fsync": after_report,
               "registered_cap_seconds": config["resource"]["preflight_wall_seconds_cap"]}
    _write_json_fsync_new(receipt_path, receipt, deadline=deadline)
    after_receipt = time.monotonic() - started
    if after_receipt > config["resource"]["preflight_wall_seconds_cap"] or receipt["status"] != "PASS":
        status = "INCOMPLETE_BUDGET"
    terminal = {
        "experiment_id": "EXP-0014", "version": "v3", "status": status,
        "source_commit": commit,
        "report_sha256": _sha(report_path), "receipt_sha256": _sha(receipt_path),
        "seconds_after_receipt_fsync": after_receipt,
        "registered_cap_seconds": config["resource"]["preflight_wall_seconds_cap"],
        "publication": {"kind": "terminal_seal_fsync",
                        "budget_class": "publication_metadata_outside_engineering_cap",
                        "started_after_receipt_seconds": after_receipt},
    }
    publication_started = time.monotonic()
    _write_json_fsync_new(terminal_path, terminal)
    report["admission_status_after_receipt"] = status
    report["seconds_after_receipt_fsync"] = after_receipt
    report["terminal_seal_publication_seconds"] = time.monotonic() - publication_started
    return report


def _verify_terminal_seal(report_path: Path, receipt_path: Path,
                          terminal: dict[str, Any], report: dict[str, Any],
                          receipt: dict[str, Any]) -> None:
    """Require a bounded post-receipt decision, independent of overrun markers."""
    if (terminal.get("experiment_id") != "EXP-0014" or terminal.get("version") != "v3"
            or terminal.get("status") != "PASS"
            or terminal.get("source_commit") != report.get("commit")
            or terminal.get("report_sha256") != _sha(report_path)
            or terminal.get("receipt_sha256") != _sha(receipt_path)
            or terminal.get("registered_cap_seconds") != receipt.get("registered_cap_seconds")
            or not isinstance(terminal.get("seconds_after_receipt_fsync"), (int, float))
            or not np.isfinite(terminal["seconds_after_receipt_fsync"])
            or terminal["seconds_after_receipt_fsync"] > terminal["registered_cap_seconds"]
            or terminal.get("publication", {}).get("budget_class")
            != "publication_metadata_outside_engineering_cap"):
        raise QualificationGateError("preflight terminal seal absent, changed or over budget")


def _admit_preflight(repo: Path, config_path: Path,
                     admission: QualificationAdmission) -> dict[str, Any]:
    report_path, receipt_path = repo / PREFLIGHT_REPORT, repo / PREFLIGHT_RECEIPT
    terminal_path = repo / PREFLIGHT_TERMINAL
    report, receipt, terminal = (_read_json(path) for path in
                                 (report_path, receipt_path, terminal_path))
    if (receipt.get("report_file") != str(report_path.resolve())
            or receipt.get("report_sha256") != _sha(report_path)
            or receipt.get("status") != "PASS" or report.get("status") != "PASS"
            or receipt.get("commit") != report.get("commit")):
        raise QualificationGateError("engineering preflight report/receipt not PASS or changed")
    _verify_terminal_seal(report_path, receipt_path, terminal, report, receipt)
    if (receipt.get("registered_cap_seconds") != _read_json(config_path)["resource"]["preflight_wall_seconds_cap"]
            or receipt.get("seconds_after_report_fsync", float("inf"))
            > receipt["registered_cap_seconds"]):
        raise QualificationGateError("engineering report fsync exceeded registered cap")
    _verified_preflight_commit(repo, report["commit"], report_path, receipt_path,
                               terminal_path)
    config = _read_json(config_path)
    if (report.get("experiment_id") != "EXP-0014" or report.get("version") != "v3"
            or report.get("config_sha256") != _sha(config_path)
            or report.get("lock_sha256") != _sha(repo / config["registration_lock_file"])
            or report.get("source_hashes") != _source_hashes(repo)
            or report.get("qualification_admission") != admission.__dict__
            or report.get("formal_task_roots_read") != 0):
        raise QualificationGateError("engineering preflight provenance differs")
    for file in (config_path, repo / config["registration_lock_file"],
                 repo / config["pair_manifest_file"],
                 repo / config["qualification_source"]["manifest_path"],
                 repo / config["qualification_source"]["analysis_path"],
                 *(repo / relative for relative in report["source_hashes"])):
        _head_blob_matches(repo, file)
    if report.get("engineering", {}).get("status") != "PASS":
        raise QualificationGateError("engineering preflight evidence is not PASS")
    engineering = report["engineering"]
    resource = config["resource"]
    if (report.get("wall_seconds", float("inf")) > resource["preflight_wall_seconds_cap"]
            or engineering.get("engineering_updates", float("inf")) > resource["engineering_update_cap"]
            or engineering.get("engineering_updates", 0) < 3 * resource["tiny_overfit_updates_per_arm"]):
        raise QualificationGateError("engineering preflight time/update cap differs")
    try:
        timings = engineering["timings_seconds"]
        ratios = {path: [float(np.median(block["RS4"]) / np.median(block["SC64"]))
                         for block in blocks] for path, blocks in timings.items()}
        step_p95 = max(float(np.percentile(block[arm], 95))
                       for block in timings["train32"] for arm in config["arms"])
        checked_resource = resource_verdict(config, engineering["accounts"], ratios,
                                            step_p95, admission.data_generation_p95_seconds)
        if checked_resource["status"] != "PASS" or not np.isclose(
            checked_resource["estimated_seconds"], engineering["verdict"]["estimated_seconds"],
            rtol=0, atol=1e-9
        ):
            raise QualificationGateError("engineering resource verdict does not recompute PASS")
        if (set(engineering["operator_profile"]) != set(config["arms"])
                or any(set(engineering["operator_profile"][arm]) != {"train32", "infer32", "infer48"}
                       for arm in config["arms"])):
            raise QualificationGateError("engineering operator profiles incomplete")
        if any(engineering["tiny_overfit"][arm]["ratio"]
               > resource["tiny_overfit_final_initial_ratio_max"] for arm in config["arms"]):
            raise QualificationGateError("engineering tiny-overfit no longer PASS")
    except (KeyError, TypeError, ValueError, FloatingPointError) as exc:
        raise QualificationGateError(f"engineering report malformed: {exc}") from exc
    return {"report_sha256": receipt["report_sha256"],
            "receipt_sha256": _sha(receipt_path), "terminal_sha256": _sha(terminal_path),
            "report_file": str(report_path), "terminal_file": str(terminal_path)}


def _deadline(deadline: float, stage: str) -> None:
    if time.monotonic() >= deadline:
        raise TimeoutError(f"EXP-0014 worker cap during {stage}")


def _batch_hash(batch: PhaseRevealBatch) -> str:
    hasher = sha256()
    for array in (batch.x, batch.oracle_pre, batch.oracle_final):
        value = np.ascontiguousarray(array)
        hasher.update(np.asarray(value.shape, dtype="<i8").tobytes())
        hasher.update(value.tobytes())
    return hasher.hexdigest()


def _seal_stage(config: dict[str, Any], stage: str, matrix: Path,
                output: Path, deadline: float,
                manifest: dict[str, Any]) -> dict[str, Any]:
    """Generate all three sealed streams for all seeds before stage training."""
    formal = config["formal"]
    task = config["task"]
    seeds = formal["model_seeds" if stage == "formal" else "replication_seeds"]
    root_keys = (("iid", "iid_root_base"), ("ood", "ood_root_base"),
                 ("retained", "retained_root_base")) if stage == "formal" else (
                     ("iid", "rep_iid_root_base"), ("ood", "rep_ood_root_base"),
                     ("retained", "rep_retained_root_base"))
    stage_dir = output / stage / "sealed"
    stage_dir.mkdir(parents=True, exist_ok=False)
    records: dict[str, Any] = {}
    manifest["sealed"][stage] = records
    for seed in seeds:
        records[str(seed)] = {}
        for split, key in root_keys:
            _deadline(deadline, f"{stage} sealing")
            root = formal[key] + seed
            retained = split == "retained"
            length = task["train_length"] if split == "iid" else task["ood_length"]
            batch = make_batch(formal["eval_examples"], length, root, matrix,
                               cue_reliability=(task["retained_cue_reliability"] if retained
                                                else task["cue_reliability"]),
                               switch_step=(task["retained_switch_step"] if retained
                                            else task["switch_step"]))
            _check_features(batch)
            path = stage_dir / f"{seed}-{split}.npz"
            np.savez_compressed(path, x=batch.x, oracle_pre=batch.oracle_pre,
                                oracle_final=batch.oracle_final, H=batch.H,
                                cue=batch.cue, u=batch.u, eps=batch.eps, y=batch.y)
            records[str(seed)][split] = {"root": root, "examples": formal["eval_examples"],
                                         "length": length, "switch_step": batch.switch_step,
                                         "cue_reliability": batch.cue_reliability,
                                         "file": str(path.relative_to(output)),
                                         "sha256": digest(path)}
            manifest["formal_task_roots_read"] += 1
            write_json(output / "manifest.json", manifest)
    return records


def _sealed_batch(output: Path, record: dict[str, Any]) -> PhaseRevealBatch:
    path = output / record["file"]
    if path.is_symlink() or digest(path) != record["sha256"]:
        raise ValueError("sealed evaluation stream hash mismatch")
    fields = ("x", "oracle_pre", "oracle_final", "H", "cue", "u", "eps", "y")
    with np.load(path, allow_pickle=False) as archive:
        if set(archive.files) != set(fields):
            raise ValueError("sealed stream fields differ")
        arrays = [np.asarray(archive[name]) for name in fields]
    if arrays[0].shape != (record["examples"], record["length"], 16):
        raise ValueError("sealed stream shape differs")
    return PhaseRevealBatch(*arrays, record["switch_step"], record["cue_reliability"])


def _save_operation(model: RoutedModel, batch: PhaseRevealBatch,
                    output: Path, seed: int, deadline: float) -> dict[str, Any]:
    output.mkdir(parents=True, exist_ok=False)
    records: dict[str, Any] = {}
    x = torch.from_numpy(batch.x)
    with torch.no_grad():
        original = model.run_trace(x, (16, 48))
    for block in range(4):
        _deadline(deadline, "state transplant")
        result = transplant_diagnostic(model, x, batch.oracle_final, block,
                                       9_930_014 + block, original)
        path = output / f"block-{block}.npz"
        arrays = {name: value for name, value in result.items()
                  if isinstance(value, np.ndarray)}
        np.savez_compressed(path, **arrays)
        records[str(block)] = {
            **{name: value for name, value in result.items()
               if not isinstance(value, np.ndarray)},
            "arrays_file": path.name, "arrays_sha256": digest(path),
        }
    return records


def _train_seed(config: dict[str, Any], admission: QualificationAdmission,
                stage: str, seed: int, sealed: dict[str, Any], matrix: Path,
                output: Path, manifest: dict[str, Any], deadline: float) -> dict[str, Any]:
    """One paired seed, common training batch, fixed final checkpoint."""
    tcfg, task = config["training"], config["task"]
    arms = tuple(config["arms"])
    seed_dir = output / stage / str(seed)
    seed_dir.mkdir(parents=True, exist_ok=False)
    models = {arm: build_model(arm, seed, config["model"]["graph_seed_base"] + seed)
              for arm in arms}
    for model in models.values():
        _check_graph(model)
    if any(not torch.equal(left, right) for left, right in zip(
        models["RS4"].parameters(), models["SC64"].parameters(), strict=True)):
        raise AssertionError("paired RS/SC initial trainable tensors differ")
    lr = {"RS4": admission.lr_rs_sc, "SC64": admission.lr_rs_sc,
          "D64_full": admission.lr_dense}
    optimizers = {arm: _optimizer(models[arm], lr[arm], tcfg) for arm in arms}
    rows = {arm: {"arm": arm, "seed": seed, "lr": lr[arm], "updates": 0,
                  "initial_state_sha256": _state_hash(models[arm]),
                  "graph": models[arm].graph_info,
                  "resources": resource_account(models[arm], task["train_length"],
                                                tcfg["batch_size"]),
                  "checkpoints": [], "status": "INCOMPLETE"} for arm in arms}
    try:
        for step in range(1, tcfg["updates_per_arm_seed"] + 1):
            _deadline(deadline, "paired training")
            root = tcfg["train_root_base"] + seed * 10_000 + step
            batch = make_batch(tcfg["batch_size"], task["train_length"], root, matrix,
                               cue_reliability=task["cue_reliability"],
                               switch_step=task["switch_step"])
            _check_features(batch)
            if step == 1:
                for arm in arms:
                    rows[arm]["first_train_root"] = root
                    rows[arm]["first_train_batch_sha256"] = _batch_hash(batch)
            x = torch.from_numpy(batch.x)
            pre = torch.from_numpy(batch.oracle_pre.astype(np.float32))
            final = torch.from_numpy(batch.oracle_final.astype(np.float32))
            for arm in arms:
                _deadline(deadline, "paired training")
                loss = _update(models[arm], optimizers[arm], x, pre, final,
                               tcfg["grad_clip"])
                rows[arm]["updates"] = step
                rows[arm]["last_loss"] = loss
                manifest["research_updates"] += 1
                if manifest["research_updates"] > config["resource"]["research_update_cap"]:
                    raise RuntimeError("formal research update cap exceeded")
            if step in tcfg["monitor_steps"]:
                index = tcfg["monitor_steps"].index(step)
                monitor_root = tcfg["monitor_root_base"] + seed * 10 + index
                monitor = make_batch(512, task["train_length"], monitor_root, matrix)
                _check_features(monitor)
                for arm in arms:
                    arm_dir = seed_dir / arm
                    arm_dir.mkdir(exist_ok=True)
                    prediction = evaluate(models[arm], monitor)
                    checkpoint = arm_dir / f"checkpoint-{step}.pt"
                    torch.save({"state_dict": models[arm].state_dict(), "arm": arm,
                                "seed": seed, "lr": lr[arm], "step": step}, checkpoint)
                    pred_path = arm_dir / f"monitor-{step}.npz"
                    rows[arm]["checkpoints"].append({
                        "step": step, "root": monitor_root,
                        "iid_final_kl": prediction["final_kl"],
                        "checkpoint_file": str(checkpoint.relative_to(output)),
                        "checkpoint_sha256": digest(checkpoint),
                        "prediction_file": str(pred_path.relative_to(output)),
                        "prediction_sha256": _save_predictions(pred_path, prediction)})
                write_json(output / "manifest.json", manifest)
        for arm in arms:
            rows[arm]["status"] = "COMPLETED"
            rows[arm]["final_state_sha256"] = _state_hash(models[arm])
            rows[arm]["evaluations"] = {}
            for split in ("iid", "ood", "retained"):
                _deadline(deadline, "sealed evaluation")
                batch = _sealed_batch(output, sealed[split])
                result = evaluate(models[arm], batch)
                path = seed_dir / arm / f"{split}.npz"
                rows[arm]["evaluations"][split] = {
                    "root": sealed[split]["root"], "examples": len(batch.x),
                    "pre_kl": result["pre_kl"], "final_kl": result["final_kl"],
                    "predictions_file": str(path.relative_to(output)),
                    "predictions_sha256": _save_predictions(path, result)}
            diagnostic_batch = _sealed_batch(output, sealed["ood"])
            with torch.no_grad():
                trace = models[arm].run_trace(torch.from_numpy(diagnostic_batch.x), (16, 48))
            diagnostic_path = seed_dir / arm / "state_diagnostic.npz"
            np.savez_compressed(diagnostic_path,
                                h16=trace["hidden_by_time"][16].numpy(),
                                h48=trace["hidden_by_time"][48].numpy(),
                                logits16=trace["logits_by_time"][16].numpy(),
                                logits48=trace["logits_by_time"][48].numpy())
            rows[arm]["state_diagnostic"] = {
                "file": str(diagnostic_path.relative_to(output)),
                "sha256": digest(diagnostic_path)}
            if arm == "RS4":
                batch = _sealed_batch(output, sealed["ood"])
                rows[arm]["operation_dir"] = str((seed_dir / arm / "operation").relative_to(output))
                rows[arm]["operation"] = _save_operation(models[arm], batch,
                    seed_dir / arm / "operation", seed, deadline)
            write_json(seed_dir / arm / "result.json", rows[arm])
        return rows
    except BaseException:
        for arm in arms:
            arm_dir = seed_dir / arm
            arm_dir.mkdir(exist_ok=True)
            checkpoint = arm_dir / "interrupted.pt"
            torch.save({"state_dict": models[arm].state_dict(), "arm": arm,
                        "seed": seed, "lr": lr[arm], "step": rows[arm]["updates"]}, checkpoint)
            rows[arm]["interrupted_checkpoint"] = str(checkpoint.relative_to(output))
            rows[arm]["interrupted_checkpoint_sha256"] = digest(checkpoint)
            write_json(arm_dir / "result.json", rows[arm])
        raise


def replay_first_seed(config_path: Path, *, repo: Path, run_path: Path,
                      report_path: Path | None = None) -> dict[str, Any]:
    """Zero-optimization replay of first formal paired seed, capped at 300s."""
    repo = Path(repo).resolve()
    run_path = Path(run_path).resolve()
    config_path = Path(config_path).resolve()
    _clean_commit(repo)
    config = _read_json(config_path)
    manifest = _read_json(run_path / "manifest.json")
    if (manifest.get("status") != "COMPLETED" or manifest.get("config_sha256") != _sha(config_path)
            or manifest.get("research_updates") != config["resource"]["research_update_cap"]):
        raise ValueError("first-seed replay requires a complete matching formal run")
    preflight = _read_json(Path(manifest["engineering_preflight"]["report_file"]))
    if preflight.get("source_hashes") != _source_hashes(repo):
        raise ValueError("replay source differs from engineering preflight")
    report_path = (report_path or run_path / "replay_first_seed.json").resolve()
    if report_path.exists():
        raise FileExistsError("replay report already exists")
    configure_cpu()
    started = time.monotonic()
    deadline = started + config["resource"]["replay_wall_seconds_cap"]
    seed = config["formal"]["model_seeds"][0]
    rows = manifest["arms"]["formal"][str(seed)]
    sealed = manifest["sealed"]["formal"][str(seed)]["ood"]
    matrix = repo / config["matrix_file"]
    root = config["training"]["train_root_base"] + seed * 10_000 + 1
    first = make_batch(config["training"]["batch_size"],
                       config["task"]["train_length"], root, matrix)
    _check_features(first)
    input_hash = _batch_hash(first)
    raw_ood = _sealed_batch(run_path, sealed)
    outcome = {}
    for arm in config["arms"]:
        _deadline(deadline, "first-seed zero-update replay")
        row = rows[arm]
        if row["first_train_root"] != root or row["first_train_batch_sha256"] != input_hash:
            raise AssertionError("first training input/root replay differs")
        model = build_model(arm, seed, config["model"]["graph_seed_base"] + seed)
        _check_graph(model)
        initial = _state_hash(model)
        if initial != row["initial_state_sha256"]:
            raise AssertionError("first seed initial weights replay differs")
        cp = row["checkpoints"][-1]
        checkpoint_path = run_path / cp["checkpoint_file"]
        if digest(checkpoint_path) != cp["checkpoint_sha256"]:
            raise AssertionError("first seed final checkpoint hash differs")
        checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
        if (checkpoint["step"] != config["training"]["updates_per_arm_seed"]
                or checkpoint["arm"] != arm or checkpoint["seed"] != seed):
            raise AssertionError("first seed checkpoint metadata differs")
        model.load_state_dict(checkpoint["state_dict"])
        if _state_hash(model) != row["final_state_sha256"]:
            raise AssertionError("first seed loaded weights differ")
        prediction = evaluate(model, raw_ood)
        record = row["evaluations"]["ood"]
        original_file = run_path / record["predictions_file"]
        if digest(original_file) != record["predictions_sha256"]:
            raise AssertionError("first seed OOD prediction archive hash differs")
        with np.load(original_file, allow_pickle=False) as archived:
            for field in ("oracle_pre", "oracle_final", "logits_pre", "logits_final"):
                if not np.array_equal(prediction[field], archived[field]):
                    raise AssertionError(f"first seed {arm} {field} replay differs")
        outcome[arm] = {"initial_state_sha256": initial,
                        "final_state_sha256": row["final_state_sha256"],
                        "prediction_archive_sha256": record["predictions_sha256"]}
    if time.monotonic() - started > config["resource"]["replay_wall_seconds_cap"]:
        raise TimeoutError("first-seed replay exceeded registered wall cap")
    report = {"experiment_id": "EXP-0014", "version": "v3", "seed": seed,
              "status": "PASS", "optimization_updates": 0,
              "first_train_root": root, "first_train_batch_sha256": input_hash,
              "arms": outcome, "seconds": time.monotonic() - started,
              "source_hashes": _source_hashes(repo),
              "manifest_sha256": _sha(run_path / "manifest.json")}
    write_json(report_path, report)
    return report


def run(config_path: Path, *, repo: Path, output: Path | None = None,
        loop_root: Path | None = None) -> dict[str, Any]:
    """Run frozen source/resource gates then both complete paired stages."""
    started = time.monotonic()
    repo = Path(repo).resolve()
    config_path = Path(config_path).resolve()
    config = _read_json(config_path)
    destination = (output or repo / config["output"]).resolve()
    if destination.exists():
        raise FileExistsError(f"formal output already exists: {destination}")
    loop_root = (loop_root or repo / "artifacts/auto_research/live").resolve()
    result: dict[str, Any] = {
        "experiment_id": "EXP-0014", "version": "v3", "config": config,
        "config_sha256": _sha(config_path), "status": "QUALIFICATION_SOURCE_NOT_READY",
        "project_root": str(repo),
        "research_updates": 0, "formal_task_roots_read": 0,
        "arms": {"formal": {}, "replication": {}},
        "sealed": {}, "runtime": {"python": platform.python_version(),
                                "torch": torch.__version__, "numpy": np.__version__,
                                "platform": platform.platform()},
    }
    destination.mkdir(parents=True, exist_ok=False)
    write_json(destination / "manifest.json", result)
    try:
        admission = qualification_gate(repo, config_path, loop_root)
    except (QualificationGateError, ValueError, KeyError, TypeError) as exc:
        result["reason"] = str(exc)
        write_json(destination / "manifest.json", result)
        return result
    result["qualification_admission"] = admission.__dict__
    try:
        preflight = _admit_preflight(repo, config_path, admission)
    except (QualificationGateError, OSError, ValueError, KeyError) as exc:
        result["status"] = "RESOURCE_UNRESOLVED"
        result["reason"] = str(exc)
        write_json(destination / "manifest.json", result)
        return result
    result["engineering_preflight"] = preflight
    result["engineering"] = _read_json(repo / PREFLIGHT_REPORT)["engineering"]
    result["status"] = "SEALED_STREAMS_PENDING"
    write_json(destination / "manifest.json", result)
    configure_cpu()
    try:
        deadline = started + config["resource"]["worker_wall_seconds_cap"]
        matrix = repo / config["matrix_file"]
        for stage in ("formal", "replication"):
            _deadline(deadline, f"{stage} start")
            result["status"] = f"SEALING_{stage.upper()}"
            write_json(destination / "manifest.json", result)
            sealed = _seal_stage(config, stage, matrix, destination, deadline, result)
            result["status"] = f"TRAINING_{stage.upper()}"
            write_json(destination / "manifest.json", result)
            seeds = config["formal"]["model_seeds" if stage == "formal" else "replication_seeds"]
            for seed in seeds:
                rows = _train_seed(config, admission, stage, seed, sealed[str(seed)],
                                   matrix, destination, result, deadline)
                result["arms"][stage][str(seed)] = rows
                write_json(destination / "manifest.json", result)
        if result["research_updates"] != config["resource"]["research_update_cap"]:
            raise AssertionError("formal research update count differs from protocol")
        result["status"] = "COMPLETED"
        result["seconds"] = time.monotonic() - started
        return result
    except TimeoutError as exc:
        result["status"] = "INCOMPLETE_BUDGET"
        result["reason"] = str(exc)
        return result
    except (FloatingPointError, AssertionError, RuntimeError, ValueError, OSError) as exc:
        result["status"] = "ENGINEERING_ABORT"
        result["reason"] = repr(exc)
        return result
    finally:
        result["seconds"] = time.monotonic() - started
        write_json(destination / "manifest.json", result)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--loop-root", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--preflight", action="store_true")
    parser.add_argument("--replay-run", type=Path)
    parser.add_argument("--replay-report", type=Path)
    args = parser.parse_args()
    if args.replay_run is not None:
        if args.preflight or args.output:
            parser.error("replay cannot be combined with preflight or formal output")
        result = replay_first_seed(args.config, repo=args.root, run_path=args.replay_run,
                                   report_path=args.replay_report)
    elif args.preflight:
        if args.output is not None:
            parser.error("--output is for formal runs, not independent preflight")
        result = run_preflight(args.config, repo=args.root, loop_root=args.loop_root)
    else:
        if args.replay_report is not None:
            parser.error("--replay-report requires --replay-run")
        result = run(args.config, repo=args.root, output=args.output, loop_root=args.loop_root)
    print(json.dumps(result, ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    main()
